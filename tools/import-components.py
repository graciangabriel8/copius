#!/usr/bin/env python3
"""Writes js/data-components.js (window.COMPONENTS) from component draft JSON files.

  python3 tools/import-components.py <json> [<json> ...]

Re-run it to refresh the data. Refuses (exit 1, nothing written) on a duplicate
id or an unknown family. Removing a component is a data edit: delete its record
from js/data-components.js (and its id from tools/free-components.json if free).
"""
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
FAMILIES = ["purees", "sauces", "emulsions", "broths", "butters-oils", "glazes",
            "crunch", "pickles", "gels", "powders", "creams", "sweet"]


def main(paths):
    if not paths:
        sys.exit(__doc__)
    recs, seen = [], set()
    for p in paths:
        for c in json.load(open(p, encoding="utf-8")):
            if c["id"] in seen:
                sys.exit("duplicate component id: %s (%s)" % (c["id"], p))
            if c["family"] not in FAMILIES:
                sys.exit("unknown family %r on %s (%s)" % (c["family"], c["id"], p))
            seen.add(c["id"])
            recs.append(c)
    recs.sort(key=lambda c: FAMILIES.index(c["family"]))  # stable: input order within a family
    head = ("/* Generated by tools/import-components.py from %s. Re-run it to refresh.\n"
            "   Removing a component = deleting its record here (and its id from\n"
            "   tools/free-components.json if it is one of the free three). */\n"
            % ", ".join(pathlib.Path(p).name for p in paths))
    body = ",\n".join(json.dumps(c, ensure_ascii=False, indent=1) for c in recs)
    (ROOT / "js" / "data-components.js").write_text(head + "window.COMPONENTS = [\n" + body + "\n];\n", encoding="utf-8")
    print("js/data-components.js: %d components" % len(recs))


main(sys.argv[1:])
