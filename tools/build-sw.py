#!/usr/bin/env python3
"""Regenerate service-worker.js from atlas.html so its cache list can never drift.
Run after changing assets:  python3 tools/build-sw.py"""
import pathlib, re, sys

root = pathlib.Path(__file__).resolve().parent.parent
# The app moved off the root: / is the holding page, the atlas is a link away.
APP = "atlas.html"
html = (root / APP).read_text()

m = re.search(r'\?v=(\d+)', html)
if not m: sys.exit("no ?v=N found in " + APP)
version = m.group(1)

assets = re.findall(r'(?:src|href)="((?:js|css)/[^"]+)"', html)
assets = sorted(set(assets))

# One URL the site does not serve fails addAll, and with it the whole install.
# Jekyll skips any _-prefixed name and the paths _config.yml excludes (the
# premium sources); a path a script builds by concatenation lands here garbled.
excluded, inside = [], False
for line in (root / "_config.yml").read_text().splitlines():
    if line.startswith("exclude:"):
        inside = True
    elif inside and re.match(r"[^\s#]", line):
        inside = False
    elif inside:
        # quoted items and trailing comments count, as they do for Jekyll and validate.js
        m = re.match(r'''^\s+-\s+["']?([^"'\s#]+)["']?\s*(#.*)?$''', line)
        if m:
            excluded.append(m.group(1))
def served(a):
    f = a.split("?")[0]
    return ((root / f).is_file() and not any(s.startswith("_") for s in f.split("/"))
            and not any(f == e or f.startswith(e.rstrip("/") + "/") for e in excluded))
unserved = [a for a in assets if not served(a)]
if unserved:
    sys.exit("%s names assets the site does not serve: %s" % (APP, ", ".join(unserved)))

extra = ["./", "./" + APP, "icons/icon-192.png", "icons/icon-512.png",
         "icons/apple-touch-icon.png", "manifest.json"]
urls = extra + assets

sw = '''/* Copius service worker — generated by tools/build-sw.py. Do not edit by hand. */
const VERSION = 'v%s';
const CACHE = 'copius-' + VERSION;
const APP_URL = './%s';
const NAV_LIMIT = 150;   // runtime entries kept beyond ASSETS, oldest evicted
const ASSETS = [
%s
];
// As cache keys report them: absolute, resolved the way addAll resolved them.
const ASSET_URLS = ASSETS.map(function (u) { return new URL(u, self.location.href).href; });

self.addEventListener('install', function (e) {
  e.waitUntil(caches.open(CACHE).then(function (c) { return c.addAll(ASSETS); }).then(function () {
    return self.skipWaiting();
  }));
});

self.addEventListener('activate', function (e) {
  e.waitUntil(caches.keys().then(function (keys) {
    return Promise.all(keys.filter(function (k) {
      return k.indexOf('copius-') === 0 && k !== CACHE;
    }).map(function (k) { return caches.delete(k); }));
  }).then(function () {
    // An /api/ answer left in this cache by an older worker would serve the
    // full version without asking the server about the session.
    return caches.open(CACHE).then(function (c) {
      return c.keys().then(function (keys) {
        return Promise.all(keys.filter(function (k) { return SKIP.test(new URL(k.url).pathname); })
          .map(function (k) { return c.delete(k); }));
      });
    });
  }).then(function () { return self.clients.claim(); }));
});

// Signing in never touches Cache Storage: the link page carries a one-time
// token, and every other /api/ answer depends on the session.
const SKIP = /^\\/(api|connexion)(\\/|$)/;

// The full version, kept for when there is no network: the bundle the server
// gave the last time it was asked (the bundle alone carries an ETag, a stub
// never does). The server is always asked first; its copy answers only when it
// cannot be reached, fails (5xx) or says « unavailable » (a database blip); only
// for the ?v= it was saved under, within PREMIUM_DAYS of being saved; and only
// to the atlas's own script tag, never to an address typed in the bar. The
// server's « ended » or « noaccess », a 401 from me.php, signing out, an atlas
// load without the sign-in marker cookie (js/app.js) and a new sign-in
// (connexion/) delete it. Kept under the PREMIUM URL, which the handlers below
// never reach, and under its own cache name, outside 'copius-', so a new
// worker version keeps it.
const PREMIUM = '/api/premium.php';
const PREMIUM_CACHE = 'premium-copius';
const PREMIUM_DAYS = 30;
function premium(e) {
  var req = e.request, v = new URL(req.url).searchParams.get('v') || '';
  function saved(fallback) {
    if (req.destination !== 'script') return Promise.resolve(fallback);
    return caches.open(PREMIUM_CACHE).then(function (c) { return c.match(PREMIUM); }).then(function (hit) {
      var at = hit ? Number(hit.headers.get('X-Saved')) : 0, now = Date.now();
      var fresh = hit && hit.headers.get('X-V') === v && at <= now && now - at < PREMIUM_DAYS * 864e5;
      return fresh ? hit : fallback;
    });
  }
  // The respondWith promise is still pending here, so the event can be kept
  // alive for the cache write: the copy is 3-4 MB, and a worker stopped as
  // soon as it answered would lose it.
  e.respondWith(fetch(req).then(function (res) {
    if (res.ok && res.headers.get('ETag')) {
      e.waitUntil(res.clone().blob().then(function (b) {
        return caches.open(PREMIUM_CACHE).then(function (c) {
          return c.put(PREMIUM, new Response(b, { headers: {
            'Content-Type': 'text/javascript; charset=utf-8', 'X-Saved': String(Date.now()), 'X-V': v } }));
        });
      }));
      return res;
    }
    if (res.status >= 500) return saved(res);
    if (!res.ok) return res;
    return res.clone().text().then(function (s) {
      if (/"(ended|noaccess)"/.test(s)) { e.waitUntil(caches.delete(PREMIUM_CACHE)); return res; }
      return /"unavailable"/.test(s) ? saved(res) : res;
    });
  }, function () { return saved(Response.error()); }));
}

self.addEventListener('fetch', function (e) {
  var req = e.request;
  if (new URL(req.url).origin !== self.location.origin) return;
  if (req.method === 'GET' && new URL(req.url).pathname === PREMIUM) { premium(e); return; }
  if (SKIP.test(new URL(req.url).pathname)) return;
  if (req.method !== 'GET') return;

  // The page itself: network first, so a new deploy is picked up. Cache is the offline fallback.
  if (req.mode === 'navigate') {
    e.respondWith(
      fetch(req).then(function (res) {
        // Only a good page is kept: a stored 404 would come back offline as
        // that URL. Keyed on the page's own URL. It used to put every
        // navigation under './index.html', so opening any second page
        // overwrote the app's offline copy with that page.
        if (res.ok) {
          var copy = res.clone();
          caches.open(CACHE).then(function (c) {
            return c.put(req, copy).then(function () { return c.keys(); }).then(function (keys) {
              // Bounded: thousands of generated pages would otherwise pile up
              // under one cache name. keys() is in insertion order, so the
              // front is the oldest. The precached assets are left alone.
              var pages = keys.filter(function (k) { return ASSET_URLS.indexOf(k.url) < 0; });
              return Promise.all(pages.slice(0, Math.max(0, pages.length - NAV_LIMIT))
                .map(function (k) { return c.delete(k); }));
            });
          });
        }
        return res;
      }).catch(function () {
        return caches.match(req).then(function (hit) { return hit || caches.match(APP_URL); });
      })
    );
    return;
  }

  // Everything else is versioned by ?v=, so cache-first is safe and instant.
  e.respondWith(
    caches.match(req).then(function (hit) {
      return hit || fetch(req).then(function (res) {
        if (res && res.status === 200) {
          var copy = res.clone();
          caches.open(CACHE).then(function (c) { c.put(req, copy); });
        }
        return res;
      });
    })
  );
});
''' % (version, APP, "\n".join("  '%s'," % u for u in urls))

(root / "service-worker.js").write_text(sw)
print("service-worker.js written — VERSION v%s, %d assets cached" % (version, len(urls)))
